"""Write every config of the final campaign from one place.

The thesis is allowed exactly six models, each called through one fixed
upstream provider with no fallback to any other model or provider:

    GPT-6.1 Sol (OpenAI), Claude Sonnet 5.5 (Anthropic),
    Gemini 3.8 Flash (Google AI Studio), Llama 3.1 8B (DeepInfra),
    Qwen3 14B (DeepInfra), DeepSeek V4.1 Flash (DeepInfra).

DeepSeek V4.1 Flash is the infrastructure model: it extracts facts, judges
answers, runs P4's memory review and the LLM contradiction check. The other five
are answer models only. Keeping the model list, the provider pins and the
per-model settings here means no config can drift from that rule.

Usage:
    python scripts/build_final_configs.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

GPT = "openrouter:openai/gpt-6.1-sol"
CLAUDE = "openrouter:anthropic/claude-sonnet-5.5"
GEMINI = "openrouter:google/gemini-3.8-flash"
LLAMA = "openrouter:meta-llama/llama-3.1-8b-instruct"
QWEN = "openrouter:qwen/qwen3-14b"
DEEPSEEK = "openrouter:deepseek/deepseek-v4.1-flash"

ANSWER_MODELS = [GPT, CLAUDE, GEMINI, LLAMA, QWEN]
SMALL = [LLAMA, QWEN]


def pin(provider: str, **extra) -> dict:
    return {"provider": {"order": [provider], "allow_fallbacks": False}, **extra}


# One provider per model, never a fallback. Reasoning settings: low effort where
# the API exposes it, Qwen thinks, the infrastructure model never reasons (its
# outputs are short labels and JSON).
EXTRAS = {
    GPT: pin("openai", reasoning={"effort": "low"}),
    CLAUDE: pin("anthropic"),
    GEMINI: pin("google-ai-studio", reasoning={"effort": "low"}),
    LLAMA: pin("deepinfra"),
    QWEN: pin("deepinfra", reasoning={"enabled": True}),
    # DeepSeek's own API may train on prompts, which this OpenRouter account's
    # privacy setting rightly excludes, so DeepSeek V4.1 Flash is served by
    # DeepInfra (fp8, no training), the same host as Llama and Qwen.
    DEEPSEEK: pin("deepinfra", reasoning={"enabled": False}),
}
ANSWER_TOKENS = {GPT: 4096, GEMINI: 4096, QWEN: 4096}

BENCH = {
    "mquake_t": "data/mquake_t_sh.json",
    "factconsolidation": "data/factconsolidation_sh_6k.json",
    "convomem": "data/convomem_changing.json",
}
POLICIES = ["NOMEM", "P0", "P1:ttl_days=20", "P2", "P3", "P4", "P5"]

COMMON = {
    "embedder": "ollama:nomic-embed-text",
    "retrieval_k": 25,
    "save_graph": True,
    "functional_predicates": "*",
    "relation_matching": "normalized",
    "extract_model": DEEPSEEK,
    "extract_retry_tokens": 4096,
    "judge_model": DEEPSEEK,
    "maintenance_model": DEEPSEEK,
    "qa_workers": 4,
    "rpm_overrides": {"openrouter": 120},
}


def extras_for(models: list[str]) -> dict:
    out = {m: EXTRAS[m] for m in models + [DEEPSEEK]}
    return out


def write(name: str, cfg: dict) -> None:
    (ROOT / "configs" / f"{name}.json").write_text(json.dumps(cfg, indent=2) + "\n")
    print("wrote configs/" + name + ".json")


def main() -> None:
    for b, data in BENCH.items():
        write(f"final_{b}", {
            "_comment": "Final matrix: five answer models x seven policies. DeepSeek V4.1 Flash extracts, "
                        "judges and maintains memory; every model is pinned to one provider with no fallback. "
                        "Generated by scripts/build_final_configs.py.",
            "dataset": data, "results_dir": f"artifacts/results/final_{b}", **COMMON,
            "models": ANSWER_MODELS, "policies": POLICIES,
            "request_extras": extras_for(ANSWER_MODELS), "answer_max_tokens": ANSWER_TOKENS,
            "budget_usd": 18.0})
        for mode in ("exact", "llm"):
            cfg = {"_comment": f"Substrate ablation: P2 with relation_matching={mode}; the normalised run is the "
                               "main matrix. Generated by scripts/build_final_configs.py.",
                   "dataset": data, "results_dir": f"artifacts/results/substrate/{b}_{mode}", **COMMON,
                   "relation_matching": mode, "models": SMALL, "policies": ["P2"],
                   "request_extras": extras_for(SMALL), "answer_max_tokens": {QWEN: 4096}, "budget_usd": 3.0}
            if mode == "llm":
                cfg.update(contradiction_model=DEEPSEEK, contradiction_candidates=8)
            write(f"substrate_{b}_{mode}", cfg)

    for tag, w in (("w631", [0.6, 0.3, 0.1]), ("w912", [0.9, 0.1, 0.2]), ("w811", [0.8, 0.1, 0.1])):
        write(f"heldout_weights_fc_{tag}", {
            "_comment": "Held-out weighting test on FactConsolidation, which the weight search never saw. "
                        "Generated by scripts/build_final_configs.py.",
            "dataset": BENCH["factconsolidation"], "results_dir": f"artifacts/results/heldout_weights_fc/{tag}",
            **COMMON, "retrieval_weights": w, "models": SMALL, "policies": ["P2"],
            "request_extras": extras_for(SMALL), "answer_max_tokens": {QWEN: 4096}, "budget_usd": 3.0})

    g = {k: v for k, v in COMMON.items() if k not in ("save_graph", "maintenance_model", "extract_model")}
    write("grace_history", {
        "_comment": "P2 grace sweep with history probes. Generated by scripts/build_final_configs.py.",
        "results_dir": "artifacts/results/grace_history", **g,
        "grace_grid": [0, 1, 3, 5, 7, 10, 14, 21, "never"],
        "benchmarks": [{"name": b, "dataset": d, "extract_model": DEEPSEEK} for b, d in BENCH.items()],
        "answer_models": SMALL, "request_extras": extras_for(SMALL), "answer_max_tokens": {QWEN: 4096}})

    workers_spec = [
        ("w0", "heads of state and heads of government, national and municipal leadership"),
        ("w1", "organizational headquarters, which city a company or institution is based in"),
        ("w2", "corporate and executive leadership, chief executives and directors"),
        ("w3", "sports team leadership, head coaches"),
        ("w4", "facts requiring combining multiple memories"),
    ]
    for mode in ("exact", "normalized", "llm"):
        cfg = {"_comment": f"RQ4: five writers share one memory, relation_matching={mode}. The writers are the "
                           "five answer models (heterogeneous extraction is the point of the shared topology); "
                           "every answering role is Gemini 3.8 Flash (low reasoning effort; it cannot be switched off), so only the memory "
                           "differs. Generated by scripts/build_final_configs.py.",
               "dataset": BENCH["mquake_t"], "results_dir": f"artifacts/results/rq4_{mode}",
               **{k: v for k, v in COMMON.items() if k not in ("extract_model", "qa_workers")},
               "relation_matching": mode, "n_agents": 5, "coverage": 0.8, "seed": 42,
               "extract_models": ANSWER_MODELS, "single_extract_model": DEEPSEEK,
               "answer_model": GEMINI, "router_model": GEMINI,
               "workers": [{"id": i, "specialty": s, "model": GEMINI} for i, s in workers_spec],
               "topologies": ["shared", "independent", "orchestrator"] if mode == "normalized" else ["shared"],
               "policies": POLICIES, "request_extras": extras_for(ANSWER_MODELS),
               "answer_max_tokens": ANSWER_TOKENS, "budget_usd": 10.0}
        if mode == "llm":
            cfg.update(contradiction_model=DEEPSEEK, contradiction_candidates=8)
        write(f"rq4_{mode}", cfg)


if __name__ == "__main__":
    main()
