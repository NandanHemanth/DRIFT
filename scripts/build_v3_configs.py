"""Write every config of the v3 final campaign (three runs) from one place.

Same six models, provider pins and per-model settings as the October final run
(scripts/build_final_configs.py). Two design changes, applied to every study:

  extract_context_lines = 4   Zep-style context (Rasmussen et al., 2025, Sec. 2.2.1):
                              the extractor sees the previous 4 lines, extracts only
                              from the current session.
  lexical = "bm25"            Okapi BM25 (Robertson and Zaragoza, 2009), rescaled to
                              [0, 1] per question, instead of word overlap.

Layout (configs/v3/ and artifacts/results/v3/):

  run1/ run2/ run3/   main matrix (7 policies x 5 models) per benchmark, and RQ4
                      (shared x 3 matching modes, independent, orchestrator) per
                      benchmark. run1 uses replicate 0; runs 2 and 3 use replicate
                      2 and 3, so every model call is made again.
  once/               follow-up studies, run once: grace period with history
                      questions, contradiction matching (exact, LLM), retrieval
                      weighting check (two sweep winners, RRF, no recency).

Usage:
    python scripts/build_v3_configs.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

GPT = "openrouter:openai/gpt-6.1-sol"
CLAUDE = "openrouter:anthropic/claude-sonnet-5.5"
GEMINI = "openrouter:google/gemini-3.8-flash"
LLAMA = "openrouter:meta-llama/llama-3.1-8b-instruct"
QWEN = "openrouter:qwen/qwen3-14b"
DEEPSEEK = "openrouter:deepseek/deepseek-v4.1-flash"
ANSWER_MODELS = [GPT, CLAUDE, GEMINI, LLAMA, QWEN]


def pin(provider: str, **extra) -> dict:
    return {"provider": {"order": [provider], "allow_fallbacks": False}, **extra}


EXTRAS = {
    GPT: pin("openai", reasoning={"effort": "low"}),
    CLAUDE: pin("anthropic"),
    GEMINI: pin("google-ai-studio", reasoning={"effort": "low"}),
    LLAMA: pin("deepinfra"),
    QWEN: pin("deepinfra", reasoning={"enabled": True}),
    DEEPSEEK: pin("deepinfra", reasoning={"enabled": False}),
}
ANSWER_TOKENS = {GPT: 4096, GEMINI: 4096, QWEN: 4096}

BENCH = {
    "mquake_t": "data/mquake_t_sh.json",
    "factconsolidation": "data/factconsolidation_sh_6k.json",
    "convomem": "data/convomem_changing.json",
}
POLICIES = ["NOMEM", "P0", "P1:ttl_days=20", "P2", "P3", "P4", "P5"]
RANKED = ["P0", "P1:ttl_days=20", "P2", "P3", "P4", "P5"]   # RQ4 ranks these six

COMMON = {
    "embedder": "ollama:nomic-embed-text",
    "retrieval_k": 25,
    "save_graph": True,
    "functional_predicates": "*",
    "relation_matching": "normalized",
    "lexical": "bm25",
    "extract_context_lines": 4,
    "extract_model": DEEPSEEK,
    "extract_retry_tokens": 4096,
    "judge_model": DEEPSEEK,
    "maintenance_model": DEEPSEEK,
    "qa_workers": 4,
    "rpm_overrides": {"openrouter": 120},
    "request_extras": {m: EXTRAS[m] for m in ANSWER_MODELS + [DEEPSEEK]},
    "answer_max_tokens": ANSWER_TOKENS,
}

# Orchestrator workers: one generic set for all three benchmarks.
WORKERS = [
    ("w0", "who holds a role or position now (leaders, managers, employers)"),
    ("w1", "places, organisations, and where people or things are based"),
    ("w2", "dates, times, schedules and appointments"),
    ("w3", "attributes and other facts about a person or thing"),
]

OUT = ROOT / "configs" / "v3"
RES = "artifacts/results/v3"


def write(rel: str, cfg: dict) -> None:
    path = OUT / f"{rel}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(cfg, indent=2) + "\n")


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    for run, replicate in ((1, 0), (2, 2), (3, 3)):
        r = f"run{run}"
        for b, data in BENCH.items():
            write(f"{r}/main_{b}", {
                "_comment": f"v3 main matrix, run {run} (replicate {replicate}). Generated by scripts/build_v3_configs.py.",
                "dataset": data, "results_dir": f"{RES}/{r}/main_{b}", **COMMON, "replicate": replicate,
                "models": ANSWER_MODELS, "policies": POLICIES})
            for mode in ("exact", "normalized", "llm"):
                cfg = {"_comment": f"v3 RQ4, run {run}, relation_matching={mode}. Five writers (the five answer "
                                   "models) share one memory per conversation; every answer model then reads it. "
                                   "Generated by scripts/build_v3_configs.py.",
                       "dataset": data, "results_dir": f"{RES}/{r}/rq4_{mode}_{b}",
                       **{k: v for k, v in COMMON.items() if k != "extract_model"},
                       "replicate": replicate, "relation_matching": mode,
                       "n_agents": 5, "coverage": 0.8, "seed": 42, "independent_agents": 3,
                       "extract_models": ANSWER_MODELS, "single_extract_model": DEEPSEEK,
                       "answer_models": ANSWER_MODELS, "router_model": GEMINI,
                       "worker_specialties": WORKERS,
                       # normalised matching runs all three topologies with the six ranked
                       # policies; the other matching modes only need P0 and P2 in shared memory
                       "topologies": ["shared", "independent", "orchestrator"] if mode == "normalized" else ["shared"],
                       "policies": RANKED if mode == "normalized" else ["P0", "P2"]}
                if mode == "llm":
                    cfg.update(contradiction_model=DEEPSEEK, contradiction_candidates=8)
                write(f"{r}/rq4_{mode}_{b}", cfg)

    for b, data in BENCH.items():
        for mode in ("exact", "llm"):
            cfg = {"_comment": f"v3 matching study: P2 with relation_matching={mode}; normalised is the main run. "
                               "Generated by scripts/build_v3_configs.py.",
                   "dataset": data, "results_dir": f"{RES}/once/matching_{mode}_{b}", **COMMON,
                   "relation_matching": mode, "models": ANSWER_MODELS, "policies": ["P2"]}
            if mode == "llm":
                cfg.update(contradiction_model=DEEPSEEK, contradiction_candidates=8)
            write(f"once/matching_{mode}_{b}", cfg)
        for tag, extra in (("w912", {"retrieval_weights": [0.9, 0.1, 0.2]}),
                           ("w811", {"retrieval_weights": [0.8, 0.1, 0.1]}),
                           ("rec0", {"retrieval_weights": [0.6, 0.3, 0.0]}),
                           ("rrf", {"retrieval_fusion": "rrf"})):
            write(f"once/weights_{tag}_{b}", {
                "_comment": f"v3 retrieval check ({tag}); 0.6/0.3/0.1 is the main run. "
                            "Generated by scripts/build_v3_configs.py.",
                "dataset": data, "results_dir": f"{RES}/once/weights_{tag}_{b}", **COMMON, **extra,
                "models": ANSWER_MODELS, "policies": ["P2"]})

    g = {k: v for k, v in COMMON.items() if k not in ("save_graph", "maintenance_model", "extract_model")}
    write("once/grace_history", {
        "_comment": "v3 P2 grace sweep with history probes. Generated by scripts/build_v3_configs.py.",
        "results_dir": f"{RES}/once/grace_history", **g,
        "grace_grid": [0, 1, 3, 5, 7, 10, 14, 21, "never"],
        "benchmarks": [{"name": b, "dataset": d, "extract_model": DEEPSEEK} for b, d in BENCH.items()],
        "answer_models": ANSWER_MODELS})
    n = len(list(OUT.rglob("*.json")))
    print(f"wrote {n} configs under configs/v3/")


if __name__ == "__main__":
    main()
